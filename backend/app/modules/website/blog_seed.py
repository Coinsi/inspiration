def main():
    with SessionLocal() as db:
        user = db.scalar(
            select(User).where(User.username == "demo", User.is_platform_admin.is_(True))
        )
        if not user:
            raise SystemExit("Development demo platform administrator required")
        count = 0
        for slug, title, category, excerpt, body in ARTICLES:
            if db.scalar(select(BlogPost.id).where(BlogPost.slug == slug)):
                continue
            data = {
                "title": title,
                "excerpt": excerpt,
                "body": body,
                "category": category,
                "author": "Inspiration 编辑部",
                "cover_media_id": None,
            }
            db.add(
                BlogPost(
                    slug=slug,
                    draft=data,
                    published=data,
                    published_at=datetime.now(UTC),
                    created_by=user.id,
                )
            )
            count += 1
        db.commit()
    print(f"Created {count} starter articles; existing articles preserved")


if __name__ == "__main__":
    main()
