import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

assert.equal(process.env.TEST_ISOLATED_PREVIEW, '1');
const base = process.env.APP_URL, out = process.env.ARTIFACT_DIR;
await mkdir(out, { recursive: true });
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1512, height: 982 }, acceptDownloads: true });
const page = await context.newPage(), errors = [], report = { checks: [] };
page.on('pageerror', e => errors.push(e.message));
try {
  const login = await context.request.post(`${base}/api/v1/auth/login`, { data: { username: 'demo', password: 'demo1234' } });
  assert.ok(login.ok());
  const token = (await login.json()).access_token;
  const call = async (method, path, data) => {
    const r = await context.request[method](`${base}/api/v1${path}`, { headers: { Authorization: `Bearer ${token}` }, data });
    assert.ok(r.ok(), await r.text()); return r.json();
  };
  const project = await call('post', '/projects', { name: `导演工作区交互验收 ${Date.now()}` }), root = `/projects/${project.id}`;
  report.project = project.id;
  await context.addInitScript(t => { localStorage.setItem('inspiration_token', t); localStorage.setItem('inspiration_theme', 'dark'); localStorage.setItem('inspiration_lang', 'zh'); }, token);
  await page.goto(`${base}${root}/director`);
  await page.getByRole('button', { name: '新建预演', exact: true }).click();
  await page.getByRole('button', { name: '室内场景', exact: true }).click();
  await page.getByLabel('预演名称', { exact: true }).fill('雨夜室内 · 双人对话');
  await page.getByRole('button', { name: '人物 A', exact: true }).click();
  assert.equal(await page.getByRole('tab', { name: '对象', exact: true }).getAttribute('aria-selected'), 'true');
  await page.getByRole('button', { name: '复制选中对象', exact: true }).click();
  assert.equal(await page.getByLabel('对象名称', { exact: true }).inputValue(), '人物 A 副本');
  assert.ok(Math.abs(Number(await page.getByLabel('位置 X', { exact: true }).inputValue()) + .3) < .001);
  await page.getByRole('button', { name: '撤销预演修改', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '人物 A 副本', exact: true }).count(), 0);
  await page.getByRole('button', { name: '重做预演修改', exact: true }).click();
  await page.getByRole('button', { name: '人物 A 副本', exact: true }).click();
  await page.getByLabel('对象名称', { exact: true }).focus();
  await page.keyboard.press('Delete');
  assert.equal(await page.getByRole('button', { name: '人物 A 副本', exact: true }).count(), 1);
  await page.getByRole('button', { name: '聚焦选中对象', exact: true }).click();
  await page.keyboard.press('Delete');
  assert.equal(await page.getByRole('button', { name: '人物 A 副本', exact: true }).count(), 0);
  await page.keyboard.press('Control+z');
  await page.getByRole('button', { name: '人物 A 副本', exact: true }).waitFor();
  await page.getByRole('button', { name: '人物 A 副本', exact: true }).click();
  await page.getByRole('button', { name: '删除选中对象', exact: true }).click();
  report.checks.push('Duplicate offsets an independent object; undo/redo and keyboard delete preserve input editing');
  await page.getByRole('button', { name: '全景', exact: true }).click();
  await page.getByRole('tab', { name: '机位', exact: true }).click();
  await page.getByRole('button', { name: '复制到结束机位', exact: true }).click();
  await page.getByRole('button', { name: '结束机位', exact: true }).click();
  assert.equal(await page.getByLabel('机位 Z', { exact: true }).inputValue(), '7');
  await page.getByLabel('机位 Z', { exact: true }).fill('4');
  await page.getByLabel('预演秒数', { exact: true }).fill('5');
  await page.keyboard.press('Control+s');
  await page.getByText('已保存版本 1', { exact: true }).waitFor();
  const scene = (await call('get', `${root}/director-scenes`))[0]; report.scene = scene.id;
  const saved = await call('get', `${root}/director-scenes/${scene.id}`);
  assert.equal(saved.document.objects.length, 4);
  assert.equal(saved.document.camera.position[2], 7);
  assert.equal(saved.document.end_camera.position[2], 4);
  report.checks.push('Copy camera and edit its independent endpoint; Ctrl+S persists exact scene');
  await page.getByRole('button', { name: '布景视角', exact: true }).click();
  await page.getByRole('button', { name: '全景', exact: true }).click();
  await page.waitForTimeout(600);
  const canvas = page.locator('canvas[aria-label="导演台3D场景"]');
  assert.ok((await canvas.boundingBox()).height > 440);
  assert.equal(await page.locator('.director-live-frame').count(), 1);
  await page.screenshot({ path: `${out}/director-workspace-dark.png` });
  const before = await canvas.screenshot();
  await page.getByRole('button', { name: '俯视', exact: true }).click();
  await page.waitForTimeout(300);
  assert.notDeepEqual(await canvas.screenshot(), before);
  await page.getByRole('button', { name: '正面', exact: true }).click();
  await page.getByRole('button', { name: '专注画面', exact: true }).click();
  assert.equal(await page.locator('.director-inspector').isVisible(), false);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.director-inspector').isVisible(), true);
  report.checks.push('Live camera inset, scene/top/front framing and focus mode work without modifying saved composition');
  await page.getByRole('button', { name: '相机取景', exact: true }).click();
  await page.getByLabel('预演进度', { exact: true }).fill('0.5');
  const capture = async name => { const p = page.waitForEvent('download'); await page.getByRole('button', { name: '下载取景图', exact: true }).click(); await (await p).saveAs(`${out}/${name}.png`); };
  await capture('without-guides');
  await page.getByRole('button', { name: '构图辅助线', exact: true }).click();
  await page.getByLabel('三分构图辅助线', { exact: true }).waitFor();
  await capture('with-guides');
  assert.deepEqual(await readFile(`${out}/with-guides.png`), await readFile(`${out}/without-guides.png`));
  await page.screenshot({ path: `${out}/director-camera-guides.png` });
  report.checks.push('Composition guides are visible only in preview; exported PNG bytes are identical');
  let exportRequests = 0;
  page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/previsualization')) exportRequests++; });
  await page.getByRole('button', { name: '导出运镜视频', exact: true }).click();
  await page.getByRole('button', { name: '取消导出', exact: true }).click();
  await page.getByText('预演导出已取消，场景保持不变', { exact: true }).waitFor();
  assert.equal(exportRequests, 0);
  assert.deepEqual((await call('get', `${root}/director-scenes/${scene.id}`)).document, saved.document);
  report.checks.push('Cancel frame rendering prevents upload and keeps saved scene intact');
  await page.getByRole('tab', { name: '灯光', exact: true }).click();
  await page.getByLabel('环境亮度', { exact: true }).fill('1.2');
  assert.equal(await page.getByRole('button', { name: '导出运镜视频', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: '撤销预演修改', exact: true }).click();
  await page.evaluate(() => { document.documentElement.classList.remove('dark'); document.documentElement.classList.add('light'); });
  await page.screenshot({ path: `${out}/director-workspace-light.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('tab', { name: '机位', exact: true }).click();
  await page.getByLabel('画面比例', { exact: true }).selectOption('9:16');
  await page.getByRole('button', { name: '相机取景', exact: true }).click();
  await page.waitForTimeout(200);
  const bounds = await page.locator('.director-composition-guides').boundingBox();
  assert.ok(Math.abs(bounds.width / bounds.height - 9 / 16) < .01);
  assert.ok(await page.locator('main').evaluate(e => e.scrollWidth <= e.clientWidth));
  await page.screenshot({ path: `${out}/director-mobile.png`, fullPage: true });
  report.checks.push('Unsaved export guard, light controls, portrait framing and 390px layout');
  assert.deepEqual(errors, []); report.passed = true;
  await writeFile(`${out}/report.json`, JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
} catch (e) {
  await page.screenshot({ path: `${out}/failure.png`, fullPage: true });
  await writeFile(`${out}/failure.json`, JSON.stringify({ ...report, error: String(e), errors }, null, 2)); throw e;
} finally { await browser.close(); }
