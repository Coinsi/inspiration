import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
assert.equal(process.env.TEST_ISOLATED_PREVIEW, '1');
const base = process.env.APP_URL, out = process.env.ARTIFACT_DIR;
const fixture = JSON.parse(await readFile(`${out}/report.json`, 'utf8'));
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const context = await browser.newContext({ viewport: { width: 1512, height: 1080 } });
const page = await context.newPage(), errors = [], report = { checks: [] };
page.on('pageerror', e => errors.push(e.message));
page.on('dialog', d => d.accept());
try {
  const login = await context.request.post(`${base}/api/v1/auth/login`, { data: { username: 'demo', password: 'demo1234' } });
  assert.ok(login.ok()); const token = (await login.json()).access_token;
  const call = async (method, path, data) => { const r = await context.request[method](`${base}/api/v1${path}`, { data, headers: { Authorization: `Bearer ${token}` } }); assert.ok(r.ok(), await r.text()); return r.json(); };
  const root = `/projects/${fixture.project}`;
  assert.equal((await call('get', root)).name, '剪辑验收 · 字幕与声音');
  await context.addInitScript(t => { localStorage.setItem('inspiration_token', t); localStorage.setItem('inspiration_lang', 'zh'); localStorage.setItem('inspiration_theme', 'dark'); }, token);
  await page.goto(`${base}${root}/cuts?timeline=${fixture.timeline}`);
  await page.getByLabel('时长 1', { exact: true }).fill('4.1');
  await page.getByRole('button', { name: '新建时间线', exact: true }).click();
  const name = `剪辑工作区交互 ${Date.now()}`;
  await page.getByLabel('时间线名称', { exact: true }).fill(name);
  await page.getByLabel('时间线名称', { exact: true }).press('Enter');
  await page.getByLabel('时间线名称', { exact: true }).waitFor({ state: 'hidden' });
  const timeline = (await call('get', `${root}/timelines`)).find(t => t.name === name);
  assert.ok(timeline); report.project = fixture.project; report.timeline = timeline.id;
  assert.equal(await page.getByLabel('工作时间线', { exact: true }).inputValue(), fixture.timeline);
  assert.equal(await page.getByLabel('时长 1', { exact: true }).inputValue(), '4.1');
  const initial = await call('get', `${root}/timelines/${fixture.timeline}/document`);
  initial.items.forEach(c => { c.transition = null; });
  const path = `${root}/timelines/${timeline.id}/document`;
  await call('put', path, { ...initial, revision: 0 });
  await page.getByLabel('工作时间线', { exact: true }).selectOption(timeline.id);
  await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.getByLabel('时长 1', { exact: true }).inputValue(), '4.1');
  await page.getByLabel('工作时间线', { exact: true }).selectOption(timeline.id);
  await page.getByRole('alertdialog').getByRole('button', { name: '确定', exact: true }).click();
  await page.getByLabel('时长 1', { exact: true }).waitFor();
  const overview = page.getByRole('region', { name: '时间线概览', exact: true });
  assert.equal(await overview.locator('.timeline-picture-block').count(), 3);
  await overview.getByRole('button', { name: '选择片段 2', exact: true }).click();
  assert.equal(await page.getByLabel('时长 1', { exact: true }).isVisible(), false);
  await page.getByLabel('时长 2', { exact: true }).fill('5');
  await page.getByRole('tab', { name: '镜头剪辑', exact: true }).focus();
  await page.keyboard.press('End');
  assert.equal(await page.getByRole('tab', { name: '保存历史', exact: true }).getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Home');
  assert.equal(await page.getByLabel('时长 2', { exact: true }).inputValue(), '5');
  await overview.getByRole('button', { name: '字幕', exact: true }).click();
  assert.equal(await page.getByLabel('字幕文字 2', { exact: true }).inputValue(), '再去看看星空与咖啡');
  await overview.getByRole('button', { name: '声音', exact: true }).click();
  assert.equal(await page.getByLabel('音量 (dB)', { exact: true }).inputValue(), '-6');
  report.checks.push('Creating a timeline retains current unsaved edits; switching asks confirmation and cancel retains them; ruler selection and keyboard tabs retain edits');
  await overview.getByRole('button', { name: '选择片段 2', exact: true }).click();
  await page.getByLabel('拆分位置 2', { exact: true }).fill('2');
  await page.getByRole('button', { name: '拆分片段', exact: true }).click();
  assert.equal(await overview.locator('.timeline-picture-block').count(), 4);
  await page.getByRole('button', { name: '复制', exact: true }).click();
  assert.equal(await overview.locator('.timeline-picture-block').count(), 5);
  await page.getByRole('button', { name: '撤销剪辑', exact: true }).click();
  assert.equal(await overview.locator('.timeline-picture-block').count(), 4);
  await page.getByRole('button', { name: '重做剪辑', exact: true }).click();
  assert.equal(await overview.locator('.timeline-picture-block').count(), 5);
  await page.getByRole('button', { name: '撤销剪辑', exact: true }).click();
  await page.getByRole('button', { name: '下移片段', exact: true }).click();
  assert.equal(await page.getByLabel('时长 3', { exact: true }).inputValue(), '2');
  await overview.getByRole('button', { name: '选择片段 1', exact: true }).click();
  await page.getByLabel('转场 1', { exact: true }).selectOption('dissolve');
  assert.ok((await overview.innerText()).includes('12.5s'));
  const before = await overview.locator('.timeline-overview-content').boundingBox();
  await page.getByRole('button', { name: '放大时间线', exact: true }).click();
  const after = await overview.locator('.timeline-overview-content').boundingBox();
  assert.ok(after.width > before.width * 1.9);
  await page.getByRole('button', { name: '缩小时间线', exact: true }).click();
  report.checks.push('Split, duplicate, undo/redo and reorder stay in sync with selection; ruler includes transition overlap and supports zoom');
  let fail = true;
  await page.route(`**/api/v1${path}`, async route => {
    if (route.request().method() !== 'PUT') return route.continue();
    await new Promise(r => setTimeout(r, 450));
    if (fail) { fail = false; return route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { message: '验收模拟：保存失败，请重试' } }) }); }
    return route.continue();
  });
  await page.getByRole('button', { name: '保存时间线', exact: true }).click();
  assert.equal(await page.getByLabel('工作时间线', { exact: true }).isDisabled(), true);
  await page.getByText(/验收模拟：保存失败/).waitFor();
  assert.equal(await page.getByLabel('时长 1', { exact: true }).inputValue(), '4');
  await page.getByRole('button', { name: '保存时间线', exact: true }).click();
  await page.getByText('已保存', { exact: true }).waitFor();
  const doc = await call('get', path);
  assert.deepEqual(doc.items.map(c => c.duration_ms), [4000, 3000, 2000, 4000]);
  assert.equal(doc.items[0].transition.duration_ms, 500);
  assert.deepEqual(doc.audio, initial.audio); assert.deepEqual(doc.subtitles, initial.subtitles);
  report.checks.push('Failed save keeps edits; pending save locks timeline switch; retry stores exact clip/audio/caption data');
  await page.getByText(/验收模拟：保存失败/).waitFor({ state: 'hidden' });
  await page.locator('main').evaluate(e => e.scrollTo(0, 0));
  await page.getByAltText('海边', { exact: true }).waitFor();
  await page.waitForFunction(() => Array.from(document.querySelectorAll('.timeline-monitor-screen img')).every(i => i.complete && i.naturalWidth > 0));
  await page.screenshot({ path: `${out}/timeline-workspace-dark.png` });
  const timelineBounds = await overview.boundingBox();
  assert.ok(timelineBounds.y < 880, 'Ruler should be available without scrolling past all clip forms');
  await overview.screenshot({ path: `${out}/timeline-overview.png` });
  await page.evaluate(() => { document.documentElement.classList.remove('dark'); document.documentElement.classList.add('light'); });
  await page.screenshot({ path: `${out}/timeline-workspace-light.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await overview.scrollIntoViewIfNeeded();
  assert.ok(await page.locator('main').evaluate(e => e.scrollWidth <= e.clientWidth));
  await page.screenshot({ path: `${out}/timeline-workspace-mobile.png` });
  await page.getByText('交付与版本对比', { exact: false }).first().click();
  assert.equal(await page.locator('.cuts-delivery-grid').isVisible(), true);
  assert.deepEqual(errors, []); report.passed = true;
  await writeFile(`${out}/workspace-report.json`, JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
} catch (e) { await page.screenshot({ path: `${out}/workspace-failure.png`, fullPage: true }); await writeFile(`${out}/workspace-failure.json`, JSON.stringify({ ...report, error: String(e), errors }, null, 2)); throw e; }
finally { await browser.close(); }
