import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
assert.equal(process.env.TEST_ISOLATED_PREVIEW, '1');
const base = process.env.APP_URL, out = process.env.ARTIFACT_DIR;
await mkdir(out, { recursive: true });
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ headless: true, channel: 'chrome' }), context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage(), errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('dialog', d => d.accept());
try {
  const login = await context.request.post(`${base}/api/v1/auth/login`, { data: { username: 'demo', password: 'demo1234' } });
  assert.ok(login.ok());
  const token = (await login.json()).access_token, headers = { Authorization: `Bearer ${token}` };
  const call = async (method, path, data) => { const r = await context.request[method](`${base}/api/v1${path}`, { headers, data }); assert.ok(r.ok(), await r.text()); return r.json(); };
  const project = await call('post', '/projects', { code: 'SKILL-DRAFT-' + Date.now(), name: '技能草稿验收 · 恢复与竞争' });
  const root = `/projects/${project.id}`;
  const skill = await call('post', root + '/skills', { name: '海边方法', description: '草稿保护验收', instructions: '先读取镜头，再核对连续性。', required_tools: ['object.read'], source: '本机验收' });
  await context.addInitScript(t => { localStorage.setItem('inspiration_token', t); localStorage.setItem('inspiration_lang', 'zh'); }, token);
  await page.goto(`${base}${root}/skills`);
  await page.getByRole('button', { name: '编辑技能 海边方法', exact: true }).click();
  const name = page.getByLabel('技能名称', { exact: true }), text = page.getByLabel('方法与步骤', { exact: true });
  await text.fill('未保存的方法草稿');
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await text.inputValue(), '未保存的方法草稿');
  await page.reload();
  await page.getByText('已恢复本机未保存的技能草稿，核对后即可继续保存。', { exact: true }).waitFor();
  assert.equal(await text.inputValue(), '未保存的方法草稿');
  assert.ok(await page.getByRole('button', { name: '归档技能', exact: true }).isDisabled());
  await call('put', root + `/skills/${skill.id}`, { name: skill.name, description: skill.description, instructions: '另一位作者保存的新方法', required_tools: skill.required_tools, source: skill.source, revision: 1 });
  const rejected = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/skills/' + skill.id));
  await page.getByRole('button', { name: '保存技能', exact: true }).click();
  assert.equal((await rejected).status(), 409);
  assert.equal(await text.inputValue(), '未保存的方法草稿');
  assert.equal((await call('get', root + `/skills/${skill.id}`)).instructions, '另一位作者保存的新方法');
  await page.screenshot({ path: `${out}/skill-draft-conflict.png`, animations: 'disabled' });
  await page.getByRole('button', { name: '载入服务器版本', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: '确定', exact: true }).click();
  await page.getByText('编辑技能 · 版本 2', { exact: true }).waitFor();
  await text.fill('核对后保存的完整方法');
  await page.route(`**/api/v1${root}/skills/${skill.id}`, async route => {
    if (route.request().method() === 'PUT') await new Promise(r => setTimeout(r, 700));
    await route.continue();
  });
  await page.getByRole('button', { name: '保存技能', exact: true }).click();
  assert.ok(await name.isDisabled());
  assert.ok(await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).isDisabled());
  assert.ok(await page.getByLabel('导入技能文件', { exact: true }).isDisabled());
  await page.getByText('已保存版本 3', { exact: true }).waitFor();
  assert.equal((await call('get', root + `/skills/${skill.id}`)).instructions, '核对后保存的完整方法');
  const remaining = await page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('skill-draft:')));
  assert.deepEqual(remaining, []);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.locator('main').evaluate(e => e.scrollWidth <= e.clientWidth));
  await page.locator('main').evaluate(e => e.scrollTop = 0);
  assert.ok(await page.getByRole('dialog').getByRole('button', {name: '关闭', exact: true}).isVisible());
  assert.ok(await name.isVisible());
  await page.screenshot({ path: `${out}/skill-editor-mobile.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('dialog').getByRole('button', {name: '关闭', exact: true}).click();
  await page.getByRole('link', { name: '导入外部目录 ↗', exact: true }).click();
  const file = page.getByLabel('选择外部目录文件', { exact: true });
  await file.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ items: [{ name: '损坏资料', summary: { invalid: true } }] })) });
  await page.getByText('请选择包含1至100项资产的有效目录', { exact: true }).waitFor();
  // Import now has its own asset-library route; keep parsing and submit locks under delay.
  await page.evaluate(() => { const original = File.prototype.text; File.prototype.text = async function() { if (this.name === 'slow.json') await new Promise(r => setTimeout(r, 700)); return original.call(this); }; });
  await file.setInputFiles({ name: 'slow.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ source: '延迟目录', items: [{ name: '海岸灯塔', type: 'location' }] })) });
  assert.ok(await file.isDisabled());
  await page.waitForTimeout(800);
  await page.getByText('海岸灯塔', { exact: true }).waitFor();
  await page.route(`**/api/v1${root}/source-catalogues/import`, async route => { await new Promise(r => setTimeout(r, 700)); await route.continue(); });
  await page.getByRole('button', { name: '导入 1 项资产信息', exact: true }).click();
  assert.ok(await file.isDisabled());
  assert.ok(await page.getByLabel('目录来源', { exact: true }).isDisabled());
  await page.getByText(/已导入 1 项资产/).waitFor();
  assert.equal((await call('get', root + '/assets')).length, 1);
  assert.deepEqual(errors, []);
  await writeFile(`${out}/draft-report.json`, JSON.stringify({ passed: true, project: project.id, skill: skill.id, checks: ['Draft close cancellation and refresh recovery', 'Revision conflict preserves local and server contents', 'Inputs locked during save, clean save clears local draft', 'Malformed catalog rejected before rendering', 'Dedicated asset import route: delayed file read and submit lock input', '390px editor layout'], errors }, null, 2));
  console.log('Skill draft and source importer regression passed');
} catch (e) { await page.screenshot({ path: `${out}/draft-failure.png`, fullPage: true }); throw e; }
finally { await browser.close(); }
